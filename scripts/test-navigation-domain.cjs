const assert=require('node:assert/strict');
const fs=require('node:fs');
(async()=>{
 const load=async path=>import('data:text/javascript;base64,'+Buffer.from(fs.readFileSync(path,'utf8')).toString('base64'));
 const {navigationContext,navigationHref}=await load(__dirname+'/../lib/navigation-context.js');
 const {fetchPublicText}=await load(__dirname+'/../lib/public-fetch.js');
 const {homeMode}=await load(__dirname+'/../lib/home-mode.js');
 const {domainSettings,canonicalRedirects}=await import('../lib/domain-config.mjs');
 let checks=0;const check=(value,label)=>{assert.ok(value,label);checks++};
 const adult={key:'adulto',base:'/',defaultSeasonKey:'2027'};
 const ctx=navigationContext('/jogos',new URLSearchParams('temporada=l3c_season_adulto_livre_2027&serie=elite'),adult);
 const link=new URL(navigationHref('/classificacao/',ctx),'https://liga3colinas.com.br');
 check(link.pathname==='/classificacao/','correct classification route');
 check(link.searchParams.get('temporada')==='l3c_season_adulto_livre_2027','season survives a menu click');
 check(link.searchParams.get('serie')==='elite','division survives a menu click');
 const historical=navigationContext('/equipes',new URLSearchParams('temporada=2026'),adult);
 check(new URL(navigationHref('/jogos/',historical),'https://example.com').searchParams.get('temporada')==='2026','explicit archive stays in 2026');
 check(navigationContext('/',new URLSearchParams(),adult).season==='2027','home uses configured default season');
 const master=navigationContext('/master/jogos',new URLSearchParams(),{key:'master',base:'/master/',defaultSeasonKey:'2026'});
 check(navigationHref('/jogos/',master)==='/master/jogos/?temporada=2026','footer remains in Master');
 check(navigationHref('/atletas/',master)==='/master/jogadores/?temporada=2026','Master athlete route is preserved');
 check(navigationHref('https://external.example/path',ctx)==='https://external.example/path','external links are unchanged');
 check(navigationHref('#equipes',ctx)==='#equipes','anchors are unchanged');
 check(navigationHref('/noticias/',ctx)==='/noticias/','global editorial pages are unchanged');
 check(navigationContext('/team/city-reapers',new URLSearchParams('s=s27'),adult).season==='s27','team links preserve the season ID');
 check(navigationContext('/temporada/2026',new URLSearchParams(),adult).season==='2026','archive path preserves 2026');
 check(homeMode({preSeason:{enabled:false}},'pre2027')==='season2027','Stats normal-season choice overrides old environment flag');
 check(homeMode({preSeason:{enabled:true}},'season2027')==='pre2027','Stats preseason choice remains explicit');
 check(homeMode({status:'ACTIVE'})==='season2027','active 2027 uses the normal season page');
 check(homeMode({status:'PLANNING'},'pre2027')==='pre2027','existing preseason remains available');
 check(homeMode(null)==='legacy2026','historical default is preserved without a 2027 setting');
 const main={NEXT_PUBLIC_SITE_URL:'https://liga3colinas.com.br',L3C_REDIRECT_OLD_DOMAIN:'true'};
 check(domainSettings(main).main,'principal origin validated');
 check(canonicalRedirects(main).length===2,'www and novo redirect to main');
 check(canonicalRedirects({NEXT_PUBLIC_SITE_URL:'https://liga3colinas.com.br'}).length===0,'staging does not redirect itself');
 assert.throws(()=>domainSettings({L3C_REDIRECT_OLD_DOMAIN:'true'}));checks++;
 assert.throws(()=>domainSettings({...main,L3C_REQUIRE_LEGACY_WORDPRESS:'true'}));checks++;
 assert.throws(()=>domainSettings({...main,L3C_LEGACY_WORDPRESS_ORIGIN:'https://liga3colinas.com.br'}));checks++;
 check(domainSettings({...main,L3C_REQUIRE_LEGACY_WORDPRESS:'true',L3C_LEGACY_WORDPRESS_ORIGIN:'https://legado.liga3colinas.com.br'}).wordpress==='https://legado.liga3colinas.com.br','legacy installation is a separate origin');
 check(await fetchPublicText('https://api.example',{},async()=>({ok:true,text:async()=>'{"ok":true}'}))==='{"ok":true}','public API response preserved');
 check(await fetchPublicText('https://api.example',{},async()=>({ok:false}))===null,'API error uses existing fallback');
 let aborted=false;
 const slow=await fetchPublicText('https://api.example',{timeoutMs:10},async(url,options)=>new Promise((resolve,reject)=>options.signal.addEventListener('abort',()=>{aborted=true;reject(Error('timeout'))},{once:true})));
 check(aborted&&slow===null,'a hung API request aborts instead of freezing navigation');
 console.log(`${checks} verificações de navegação, temporadas, timeout e domínio: OK`);
})().catch(error=>{console.error(error);process.exitCode=1});
